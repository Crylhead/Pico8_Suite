#!/usr/bin/env python3
"""Materialize pinned, local-only Minifier assets. No npm/build step or runtime CDN."""
import argparse
import base64
import hashlib
import io
import json
import pathlib
import tarfile
import urllib.request
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
# index.html opened directly (file://, #162) cannot fetch these files, so they are also written as
# classic scripts: the large runtime bundle (Git-ignored, beside the runtime) and the small,
# committed Suite sources + pins (kept identical to the .py files and the lock by a test).
FILE_ASSETS = 'vendor/pyodide/runtime/file-assets.js'
SUITE_SOURCES = 'vendor/shrinko8/suite-sources.js'


def verify(data, expected, label):
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError(f"SHA-256 mismatch: {label}; no asset was installed")


def archive_bytes(record, local):
    if local:
        data = pathlib.Path(local).read_bytes()
    else:
        with urllib.request.urlopen(record['url'], timeout=90) as response:
            data = response.read()
    verify(data, record['sha256'], record['url'])
    return data


def prepare(lock, shrinko_archive, pyodide_archive):
    """Verify everything before writing; never extract arbitrary archive paths or links."""
    assets = {}
    shrinko = lock['shrinko8']
    with tarfile.open(fileobj=io.BytesIO(shrinko_archive)) as source:
        prefix = 'shrinko8-' + shrinko['commit'] + '/'
        bundle = io.BytesIO()
        with zipfile.ZipFile(bundle, 'w', compression=zipfile.ZIP_STORED) as output:
            for name in shrinko['modules']:
                if '/' in name or '\\' in name or not name.endswith('.py'):
                    raise ValueError('Invalid engine module name')
                entry = source.getmember(prefix + name)
                if not entry.isfile():
                    raise ValueError('Engine source is not a regular file')
                info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
                info.create_system = 3
                info.external_attr = 0o100644 << 16
                output.writestr(info, source.extractfile(entry).read())
        data = bundle.getvalue()
        verify(data, shrinko['bundleSha256'], 'Shrinko8 module bundle')
        assets['vendor/shrinko8/runtime/engine.zip'] = data
    with tarfile.open(fileobj=io.BytesIO(pyodide_archive)) as source:
        for name, expected in lock['pyodide']['files'].items():
            if '/' in name or '\\' in name:
                raise ValueError('Invalid runtime asset name')
            entry = source.getmember('package/' + name)
            if not entry.isfile():
                raise ValueError('Runtime asset is not a regular file')
            data = source.extractfile(entry).read()
            verify(data, expected['sha256'], name)
            if len(data) != expected['bytes']:
                raise ValueError('Runtime size mismatch: ' + name)
            assets['vendor/pyodide/runtime/' + name] = data
    return assets


def install(assets, root=ROOT):
    """Install a fully verified asset set; shared by packaging and the local launcher."""
    for name, data in assets.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_suffix(path.suffix + '.tmp')
        temporary.write_bytes(data)
        temporary.replace(path)


def asset_problems(root, lock):
    """Installed runtime files that are missing or differ from the lock (empty list = verified)."""
    records = {'vendor/shrinko8/runtime/engine.zip': {'sha256': lock['shrinko8']['bundleSha256']}}
    for name, record in lock['pyodide']['files'].items():
        if '/' in name or '\\' in name or name in ('.', '..'):
            raise ValueError('Invalid runtime asset name')
        records['vendor/pyodide/runtime/' + name] = record
    problems = []
    for name, record in records.items():
        try:
            data = (root / name).read_bytes()
            if hashlib.sha256(data).hexdigest() != record['sha256'] or ('bytes' in record and len(data) != record['bytes']):
                problems.append(name)
        except OSError:
            problems.append(name)
    return problems


def suite_sources_text(root=ROOT):
    """Committed classic script with the bridge sources and the pins file:// verification needs."""
    lock = json.loads((root / 'vendor/minifier-lock.json').read_text(encoding='utf-8'))
    data = {
        'pins': {'pyodideVersion': lock['pyodide']['version'], 'pythonVersion': lock['pyodide']['pythonVersion'],
                 'shrinko8Version': lock['shrinko8']['version'], 'shrinko8Commit': lock['shrinko8']['commit'],
                 'bundleSha256': lock['shrinko8']['bundleSha256']},
        'python': {name: (root / 'vendor/shrinko8' / name).read_bytes().decode('utf-8').replace('\r\n', '\n')
                   for name in ('suite_bridge.py', 'suite_png.py')},
    }
    return ('// Generated by tools/package_minifier.py from vendor/minifier-lock.json and vendor/shrinko8/*.py.\n'
            '// Used when index.html is opened directly (file://, #162). Do not edit; regenerate.\n'
            'self.P8MinifierSuiteSources = ' + json.dumps(data, indent=1, ensure_ascii=False) + ';\n')


def file_assets_text(root=ROOT):
    """Git-ignored classic script embedding the verified runtime for file:// pages."""
    lock = json.loads((root / 'vendor/minifier-lock.json').read_text(encoding='utf-8'))
    problems = asset_problems(root, lock)
    if problems:
        raise ValueError('Runtime files are missing or unverified: ' + ', '.join(problems))
    runtime = root / 'vendor/pyodide/runtime'
    text = lambda path: path.read_bytes().decode('utf-8')
    b64 = lambda path: base64.b64encode(path.read_bytes()).decode('ascii')
    data = {'format': 1, 'pyodideVersion': lock['pyodide']['version'], 'bundleSha256': lock['shrinko8']['bundleSha256'], 'files': {
        'pyodide.mjs': text(runtime / 'pyodide.mjs'), 'pyodide.asm.mjs': text(runtime / 'pyodide.asm.mjs'),
        'pyodide-lock.json': text(runtime / 'pyodide-lock.json'),
        'pyodide.asm.wasm': b64(runtime / 'pyodide.asm.wasm'), 'python_stdlib.zip': b64(runtime / 'python_stdlib.zip'),
        'engine.zip': b64(root / 'vendor/shrinko8/runtime/engine.zip')}}
    return ('// Generated by tools/package_minifier.py from the verified pinned runtime (#162). Git-ignored.\n'
            'self.P8MinifierFileAssets = ' + json.dumps(data) + ';\n')


def write_file_mode(root=ROOT):
    """Write both file:// scripts atomically; the committed one only when its content changed."""
    outputs = {SUITE_SOURCES: suite_sources_text(root), FILE_ASSETS: file_assets_text(root)}
    for name, text in outputs.items():
        path = root / name
        data = text.encode('utf-8')
        if path.is_file() and path.read_bytes().replace(b'\r\n', b'\n') == data:
            continue  # unchanged (a Windows checkout may hold the committed file with CRLF)
        temporary = path.with_suffix(path.suffix + '.tmp')
        temporary.write_bytes(data)
        temporary.replace(path)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--shrinko-archive', help='Use the pinned .tar.gz from disk instead of downloading')
    parser.add_argument('--pyodide-archive', help='Use the pinned .tgz from disk instead of downloading')
    parser.add_argument('--force', action='store_true', help='Download/unpack again even if the installed runtime verifies')
    args = parser.parse_args()
    lock = json.loads((ROOT / 'vendor/minifier-lock.json').read_text())
    if args.force or args.shrinko_archive or args.pyodide_archive or asset_problems(ROOT, lock):
        assets = prepare(lock, archive_bytes(lock['shrinko8'], args.shrinko_archive),
                         archive_bytes(lock['pyodide'], args.pyodide_archive))
        install(assets)
        print(f"Installed {len(assets)} verified assets ({sum(map(len, assets.values())):,} bytes).")
    else:
        print('Pinned Minifier runtime already installed and verified; no download needed.')
    write_file_mode()
    print('Ready: open index.html directly (no server needed), or use the optional local launcher.')


if __name__ == '__main__':
    main()
