// js/datatools.js
// Converters workspace: ports of binary_data_converter (bytes -> PICO-8 string
// literal) and nibble_converter (greyscale -> hi/lo nibble images), wired to the library.

'use strict';

(() => {
  const App = window.P8App;
  const S = window.Suite;
  const { rgbOf, encodeIndexedPng } = P8;
  const { el, $, showMessage, toast, download, pickFile, decodeImage, sanitizeFilename } = App;

  // ------------------------------------------------------------------ //
  // Binary -> PICO-8 string (bin_data_convert.py)                      //
  // ------------------------------------------------------------------ //

  /** Safe ASCII (32–126 except " and \) as is, everything else as \ddd (3 digits). */
  function encodeP8String(bytes) {
    let out = '';
    for (const b of bytes) {
      if (b >= 32 && b <= 126 && b !== 34 && b !== 92) out += String.fromCharCode(b);
      else out += `\\${String(b).padStart(3, '0')}`;
    }
    return out;
  }

  function sanitizeVarName(name) {
    name = name.trim() || 'data';
    let clean = '';
    for (let i = 0; i < name.length; i++) {
      const ch = name[i];
      clean += /[A-Za-z_]/.test(ch) || (i > 0 && /[0-9]/.test(ch)) ? ch : '_';
    }
    if (/^[0-9]/.test(clean)) clean = `v${clean}`;
    return clean;
  }

  function generateSnippet(bytes, varName, sourceDesc) {
    const v = sanitizeVarName(varName);
    return [
      '-- auto-generated by p8bindata_gui',
      `-- source: ${sourceDesc} (${bytes.length} bytes)`,
      `${v}_len = ${bytes.length}`,
      `${v}_str = "${encodeP8String(bytes)}"`,
      '',
      `function ${v}_byte(i)`,
      `  return ord(${v}_str, i)`,
      'end',
      '',
    ].join('\n');
  }

  /** Image asset -> bytes: 4bpp (PICO-8 memory order, left pixel in the low nibble) or 1 byte per pixel. */
  function imageBytes(a, layout) {
    if (layout === '8bpp') return Uint8Array.from(a.pixels, (v) => v & 15);
    const rowBytes = Math.ceil(a.w / 2);
    const out = new Uint8Array(rowBytes * a.h);
    for (let y = 0; y < a.h; y++) {
      for (let x = 0; x < a.w; x += 2) {
        const lo = a.pixels[y * a.w + x] & 15;
        const hi = x + 1 < a.w ? a.pixels[y * a.w + x + 1] & 15 : 0;
        out[y * rowBytes + (x >> 1)] = lo | (hi << 4);
      }
    }
    return out;
  }

  const bin = {
    mode: 'file',
    file: null,      // {name, bytes}
    asset: null,
    output: '',
  };

  const bdom = {
    mode: $('#bdMode'),
    fileRow: $('#bdFileRow'),
    fileName: $('#bdFileName'),
    textRow: $('#bdTextRow'),
    text: $('#bdText'),
    imageRow: $('#bdImageRow'),
    imageName: $('#bdImageName'),
    imageThumb: $('#bdImageThumb'),
    layout: $('#bdLayout'),
    varName: $('#bdVar'),
    out: $('#bdOut'),
    info: $('#bdInfo'),
  };

  function renderBin() {
    for (const b of bdom.mode.querySelectorAll('button')) b.setAttribute('aria-checked', String(b.dataset.value === bin.mode));
    bdom.fileRow.hidden = bin.mode !== 'file';
    bdom.textRow.hidden = bin.mode !== 'text';
    bdom.imageRow.hidden = bin.mode !== 'image';
    bdom.fileName.textContent = bin.file ? `${bin.file.name} (${bin.file.bytes.length} bytes)` : 'No file selected';
    bdom.imageName.textContent = bin.asset ? `${bin.asset.name} (${bin.asset.w}×${bin.asset.h})` : 'No image selected';
    bdom.imageThumb.replaceChildren(...(bin.asset ? [S.thumbnail(bin.asset, 48)] : []));
  }

  function convertBin() {
    let bytes;
    let desc;
    const v = sanitizeVarName(bdom.varName.value);
    if (bin.mode === 'file') {
      if (!bin.file) { showMessage('Convert', 'Please select a file.'); return; }
      bytes = bin.file.bytes;
      desc = `file ${bin.file.name}`;
    } else if (bin.mode === 'text') {
      bytes = new TextEncoder().encode(bdom.text.value);
      desc = 'text input';
    } else {
      if (!bin.asset) { showMessage('Convert', 'Please choose an image from the library.'); return; }
      const a = S.assets.get(bin.asset.id) || bin.asset;
      const layout = bdom.layout.value;
      bytes = imageBytes(a, layout);
      desc = `image ${a.name} ${a.w}x${a.h} ${layout === '8bpp' ? '1 byte per pixel' : '4bpp, pico-8 memory layout'}`;
    }
    let text = generateSnippet(bytes, v, desc);
    if (bin.mode === 'image') {
      const a = bin.asset;
      text += bdom.layout.value === '8bpp'
        ? ['', `-- pixel (x,y) of the ${a.w}x${a.h} image`, `function ${v}_pget(x,y)`, `  return ord(${v}_str, y*${a.w}+x+1)`, 'end', ''].join('\n')
        : ['', `-- copy to memory, e.g. ${v}_poke(0x0000) for the sprite sheet`, `-- (${a.w === 128 ? 'rows line up with the 128 px wide sheet' : `rows are ${Math.ceil(a.w / 2)} bytes, the sheet has 64`})`,
          `function ${v}_poke(addr)`, `  for i=1,${v}_len do poke(addr+i-1, ord(${v}_str, i)) end`, 'end', ''].join('\n');
    }
    bin.output = text;
    bdom.out.value = text;
    bdom.info.textContent = `${bytes.length} bytes → ${text.length} characters of code (counts toward the 65535 character limit; tokens: 1 per string)`;
  }

  async function chooseFile() {
    const file = await pickFile('*/*');
    if (!file) return;
    bin.file = { name: file.name, bytes: new Uint8Array(await file.arrayBuffer()) };
    if (!bdom.varName.value.trim() || bdom.varName.dataset.auto === '1') {
      bdom.varName.value = sanitizeVarName(file.name.replace(/\.[^.]+$/, ''));
      bdom.varName.dataset.auto = '1';
    }
    renderBin();
  }

  async function chooseImage(a = null) {
    a = a || (await S.pickAsset({ title: 'Binary → String: Image from Library' }));
    if (!a) return;
    bin.asset = a;
    bin.mode = 'image';
    if (!bdom.varName.value.trim() || bdom.varName.dataset.auto === '1') {
      bdom.varName.value = sanitizeVarName(a.name);
      bdom.varName.dataset.auto = '1';
    }
    renderBin();
  }

  async function copyOut() {
    if (!bin.output) return;
    try {
      await navigator.clipboard.writeText(bin.output);
    } catch {
      bdom.out.select();
      document.execCommand('copy');
    }
    toast('Copied to clipboard');
  }

  // ------------------------------------------------------------------ //
  // Nibble split (nibble_converter)                                    //
  // ------------------------------------------------------------------ //

  const nib = { name: '', w: 0, h: 0, gray: null, hi: null, lo: null };

  const ndom = {
    drop: $('#nbDrop'),
    orig: $('#nbOrig'),
    hi: $('#nbHi'),
    lo: $('#nbLo'),
    info: $('#nbInfo'),
    actions: $('#nbActions'),
  };

  const lum = (r, g, b) => Math.max(0, Math.min(255, Math.trunc(0.299 * r + 0.587 * g + 0.114 * b)));

  function setGray(gray, w, h, name) {
    nib.name = name;
    nib.w = w;
    nib.h = h;
    nib.gray = gray;
    nib.hi = Uint8Array.from(gray, (g) => (g >> 4) & 15);
    nib.lo = Uint8Array.from(gray, (g) => g & 15);
    renderNibble();
  }

  function paint(canvas, w, h, valueAt) {
    canvas.width = w;
    canvas.height = h;
    const img = new ImageData(w, h);
    for (let i = 0; i < w * h; i++) {
      const c = valueAt(i);
      img.data.set([c[0], c[1], c[2], 255], i * 4);
    }
    canvas.getContext('2d').putImageData(img, 0, 0);
  }

  function renderNibble() {
    const has = !!nib.gray;
    ndom.actions.hidden = !has;
    ndom.drop.hidden = has;
    for (const c of [ndom.orig, ndom.hi, ndom.lo]) c.hidden = !has;
    if (!has) { ndom.info.textContent = ''; return; }
    const std = Array.from({ length: 16 }, (_, i) => rgbOf(i));
    paint(ndom.orig, nib.w, nib.h, (i) => [nib.gray[i], nib.gray[i], nib.gray[i]]);
    paint(ndom.hi, nib.w, nib.h, (i) => std[nib.hi[i]]);
    paint(ndom.lo, nib.w, nib.h, (i) => std[nib.lo[i]]);
    ndom.info.textContent = `${nib.name} · ${nib.w}×${nib.h} · greyscale 0–255 split into high and low 4 bits (shown as PICO-8 colors 0–15)`;
  }

  async function nibbleFromFile(file = null) {
    file = file || (await pickFile('image/png,image/jpeg,image/bmp,image/gif,.png,.jpg,.jpeg,.bmp,.gif'));
    if (!file) return;
    let img;
    try {
      img = await decodeImage(file);
    } catch {
      showMessage('Nibble Split', 'Could not decode the image.');
      return;
    }
    if (img.width > S.MAX_IMAGE_SIDE || img.height > S.MAX_IMAGE_SIDE) {
      showMessage('Nibble Split', `Images up to ${S.MAX_IMAGE_SIDE}×${S.MAX_IMAGE_SIDE} are supported.`);
      return;
    }
    const gray = new Uint8Array(img.width * img.height);
    for (let i = 0; i < gray.length; i++) gray[i] = lum(img.data[i * 4], img.data[i * 4 + 1], img.data[i * 4 + 2]);
    setGray(gray, img.width, img.height, file.name.replace(/\.[^.]+$/, ''));
  }

  function nibbleFromAsset(a) {
    const rgb = S.paletteRgb(a.pal);
    setGray(Uint8Array.from(a.pixels, (s) => lum(...rgb[s & 15])), a.w, a.h, a.name);
  }

  async function nibbleFromLibrary() {
    const a = await S.pickAsset({ title: 'Nibble Split: Image from Library' });
    if (a) nibbleFromAsset(a);
  }

  const stacked = () => {
    const out = new Uint8Array(nib.w * nib.h * 2);
    out.set(nib.hi, 0);
    out.set(nib.lo, nib.w * nib.h);
    return out;
  };

  async function nibbleToLibrary(which) {
    if (!nib.gray) return;
    const put = (suffix, pixels, h = nib.h) => S.assets.put(S.imageAsset({ name: `${nib.name}_${suffix}`, w: nib.w, h, pixels, source: 'nibble', transparent: -1 }));
    try {
      if (which === 'stacked') {
        if (nib.h * 2 > S.MAX_IMAGE_SIDE) { showMessage('Nibble Split', 'The stacked image would be too tall for the library.'); return; }
        await put('nibbles', stacked(), nib.h * 2);
      } else {
        await put('hi', nib.hi.slice());
        await put('lo', nib.lo.slice());
      }
    } catch (e) { S.reportStorageError('Nibble Split', e); return; }
    toast('Saved to the library');
  }

  async function nibbleDownload(which) {
    if (!nib.gray) return;
    const std = Array.from({ length: 16 }, (_, i) => rgbOf(i));
    const base = sanitizeFilename(nib.name || 'nibbles');
    if (which === 'stacked') download(await encodeIndexedPng(nib.w, nib.h * 2, stacked(), std), `${base}_nibbles.png`);
    else download(await encodeIndexedPng(nib.w, nib.h, which === 'hi' ? nib.hi : nib.lo, std), `${base}_${which}.png`);
  }

  // ------------------------------------------------------------------ //
  // Binding + registration                                             //
  // ------------------------------------------------------------------ //

  function bind() {
    bdom.mode.addEventListener('click', (e) => {
      const b = e.target.closest('button[data-value]');
      if (!b) return;
      bin.mode = b.dataset.value;
      renderBin();
    });
    $('#bdChooseFile').addEventListener('click', chooseFile);
    $('#bdChooseImage').addEventListener('click', () => chooseImage());
    $('#bdConvert').addEventListener('click', convertBin);
    $('#bdCopy').addEventListener('click', copyOut);
    $('#bdDownload').addEventListener('click', () => {
      if (bin.output) download(bin.output, `${sanitizeVarName(bdom.varName.value)}.lua`);
    });
    bdom.varName.addEventListener('input', () => { bdom.varName.dataset.auto = '0'; });
    S.bindAssetDrop($('#bdCard'), (a) => { if (a.kind === 'image') chooseImage(a); });

    $('#nbFile').addEventListener('click', () => nibbleFromFile());
    $('#nbLibrary').addEventListener('click', nibbleFromLibrary);
    $('#nbToLib').addEventListener('click', () => nibbleToLibrary('pair'));
    $('#nbStackToLib').addEventListener('click', () => nibbleToLibrary('stacked'));
    $('#nbDlHi').addEventListener('click', () => nibbleDownload('hi'));
    $('#nbDlLo').addEventListener('click', () => nibbleDownload('lo'));
    $('#nbDlStack').addEventListener('click', () => nibbleDownload('stacked'));
    const card = $('#nbCard');
    card.addEventListener('dragover', (e) => {
      if ([...(e.dataTransfer?.types || [])].includes('Files')) { e.preventDefault(); card.classList.add('dragover'); }
    });
    card.addEventListener('dragleave', () => card.classList.remove('dragover'));
    card.addEventListener('drop', (e) => {
      card.classList.remove('dragover');
      const f = e.dataTransfer?.files?.[0];
      if (!f) return;
      e.preventDefault();
      nibbleFromFile(f);
    });
    S.bindAssetDrop(card, (a) => { if (a.kind === 'image') nibbleFromAsset(a); });
  }

  S.registerTool({
    ws: 'data', category: 'utilities', name: 'Converters',
    desc: 'Binary → PICO-8 string literals (files, text or library images) and greyscale nibble splitting.',
    tasks: [{ group: 'create', label: 'Turn a file or image into a Lua string', hint: 'Binary → PICO-8 string, nibble split' }], color: '#ffa300', tags: ['bytes', 'strings', 'nibbles'], category: 'utilities',
  });
  S.registerConsumer({ id: 'data-bin', label: 'Binary → String', kinds: ['image'], open: (a) => { App.setWorkspace('data'); chooseImage(a); } });
  S.registerConsumer({ id: 'data-nibble', label: 'Nibble Split', kinds: ['image'], open: (a) => { App.setWorkspace('data'); nibbleFromAsset(a); } });

  bind();
  renderBin();
  renderNibble();
})();
